def t(key: str, lang: str = "ENGLISH", **kwargs) -> str:
    lang = (lang or "ENGLISH").upper()
    if lang not in ["ENGLISH", "HINGLISH", "GUJLISH"]:
        lang = "ENGLISH"
        
    translations_for_key = TRANSLATIONS.get(key)
    if not translations_for_key:
        return f"[{key}]"
        
    template = translations_for_key.get(lang, translations_for_key.get("ENGLISH", f"[{key}]"))
    try:
        return template.format(**kwargs)
    except KeyError as e:
        print(f"Translation KeyError for key '{key}', lang '{lang}': {e}")
        return template
